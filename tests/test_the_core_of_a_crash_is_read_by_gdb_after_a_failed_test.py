"""TEMPORARY, with tests/_crash_cores.py: after a test that fails, gdb's text of every core in `$INVPW_CORE_DIR` is in the evidence and the core is gone.

The exit by SIGSEGV (-11) of the engine in generate mode (runs 44985244053 and 45014369018) left no core: a release build crashes in silence, and only a core tells a
wanted crash (`gMozCrashReason`) from a bad access. tests/conftest.py lifts the core limit of the session on Linux and calls `_crash_cores.after_the_report` from
`pytest_runtest_makereport` after each phase of every test. Here the hook itself runs, with a fake core file and a fake gdb (a script of this Python that logs how
it was called and answers like gdb), so it is proved on every system, no browser:

* a phase that fails: the conftest hook hands the report back unchanged, gdb is given the executable the core's header names, the core and every command the
  diagnosis needs (all the threads' backtraces and names, the signal's address, `gMozCrashReason`, the shared libraries), its text is saved under
  `cores/<test>/` with notes, and the core is deleted;
* when the header names no file, the executable is `$INVPW_BINARY_PATH`;
* a core left after a test that passed is deleted and listed in `cores/after-passing-tests.txt`, and gdb is not run; a core found at the teardown of a test that
  failed in its call is read like one found at the failure;
* the controls: without `$INVPW_CORE_DIR` nothing is written and the core is left; a failure with no core says so; on Linux the session's soft core limit is the
  hard one, elsewhere lifting it is a no-op that does not raise.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

import _crash_cores

pytestmark = pytest.mark.unit

NODEID = "tests/test_some_engine_e2e.py::test_it[in-process]"
CORE = "core.Socket Thread.4242"

_FAKE_GDB = r'''
import json, os, sys
with open(os.environ["FAKE_GDB_LOG"], "a") as log:
    log.write(json.dumps(sys.argv[1:]) + "\n")
sys.stdout.write("Core was generated by `%s -contentproc 7 socket'.\n" % os.environ["FAKE_GDB_NAMES"])
sys.stdout.write("Program terminated with signal SIGSEGV, Segmentation fault.\n")
if "-ex" in sys.argv:
    sys.stdout.write("#0  0x00007f0000001234 in FakeCrash () from /fake/libxul.so\n")
'''


@pytest.fixture
def fake(tmp_path, monkeypatch):
    """A core folder with one fake core, the evidence under `tmp_path/runner`, a fake gdb in place of gdb, an engine file the header names."""
    cores = tmp_path / "cores-dir"
    cores.mkdir()
    (cores / CORE).write_bytes(b"\x7fELF fake core")
    engine = tmp_path / "engine" / "firefox"
    engine.parent.mkdir()
    engine.write_bytes(b"fake engine")
    script = tmp_path / "fake_gdb.py"
    script.write_text(_FAKE_GDB, encoding="utf-8")
    log = tmp_path / "gdb-calls.jsonl"
    monkeypatch.setenv("RUNNER_TEMP", str(tmp_path / "runner"))
    monkeypatch.setenv("INVPW_CORE_DIR", str(cores))
    monkeypatch.setenv("FAKE_GDB_LOG", str(log))
    monkeypatch.setenv("FAKE_GDB_NAMES", str(engine))
    monkeypatch.delenv("INVPW_BINARY_PATH", raising=False)
    monkeypatch.delenv("STEALTHFOX_E2E_BINARY", raising=False)
    monkeypatch.setattr(_crash_cores, "gdb", lambda: [sys.executable, "-I", str(script)])
    monkeypatch.setattr(_crash_cores, "_FAILED", set())
    evidence = tmp_path / "runner" / "invpw-evidence" / "cores"
    return SimpleNamespace(cores=cores, core=cores / CORE, engine=engine, log=log, evidence=evidence, folder=evidence / _crash_cores.folder_name(NODEID))


def _calls(fake):
    return [json.loads(line) for line in fake.log.read_text(encoding="utf-8").splitlines()] if fake.log.is_file() else []


def _the_conftest_hook(request):
    for plugin in request.config.pluginmanager.get_plugins():
        if Path(getattr(plugin, "__file__", "") or "").name == "conftest.py" and hasattr(plugin, "pytest_runtest_makereport"):
            return plugin.pytest_runtest_makereport
    raise AssertionError("no conftest.py has a pytest_runtest_makereport hook")


def _through_the_hook(hook, when, failed):
    """Drives the conftest wrapper as pluggy does: the report goes in at its yield and must come out unchanged."""
    report = SimpleNamespace(when=when, failed=failed)
    run = hook(item=SimpleNamespace(nodeid=NODEID), call=None)
    next(run)
    with pytest.raises(StopIteration) as stop:
        run.send(report)
    assert stop.value.value is report, "the hook did not hand the report back"


def test_a_failed_phase_has_its_core_read_by_gdb_through_the_conftest_hook_and_deleted(fake, request):
    hook = _the_conftest_hook(request)
    _through_the_hook(hook, "setup", False)
    assert fake.core.is_file() and not _calls(fake), "a phase that passed read or deleted the core"
    _through_the_hook(hook, "call", True)
    calls = _calls(fake)
    assert len(calls) == 2, calls  # the header, then the full read
    full = calls[-1]
    commands = [full[index + 1] for index, part in enumerate(full) if part == "-ex"]
    for needed in ("thread apply all bt", "info threads", "p $_siginfo._sifields._sigfault.si_addr", "x/s *(char**)&gMozCrashReason", "info sharedlibrary"):
        assert needed in commands, (needed, commands)
    assert full[-3:] == [str(fake.engine), "-c", str(fake.core)], full
    text = (fake.folder / (CORE + ".gdb.txt")).read_text(encoding="utf-8")
    assert "#0  0x00007f0000001234 in FakeCrash ()" in text and "from the core's header" in text, text
    notes = (fake.folder / "notes.txt").read_text(encoding="utf-8")
    assert NODEID in notes and "phase call" in notes and "gdb exited 0" in notes, notes
    assert not fake.core.exists(), "the core was not deleted after gdb read it"
    _through_the_hook(hook, "teardown", False)
    assert len(_calls(fake)) == 2 and not (fake.evidence / _crash_cores.AFTER_PASSING).exists()


def test_when_the_header_names_no_file_the_executable_is_the_binary_of_the_run(fake, monkeypatch):
    monkeypatch.setenv("FAKE_GDB_NAMES", str(fake.engine.parent / "not-there"))
    monkeypatch.setenv("INVPW_BINARY_PATH", str(fake.engine))
    _crash_cores.after_the_report(NODEID, "call", True)
    full = _calls(fake)[-1]
    assert full[-3:] == [str(fake.engine), "-c", str(fake.core)], full
    assert "from $INVPW_BINARY_PATH" in (fake.folder / (CORE + ".gdb.txt")).read_text(encoding="utf-8")


def test_a_core_left_by_a_test_that_passed_is_deleted_and_listed_and_one_at_the_teardown_of_a_failed_test_is_read(fake):
    for when in ("setup", "call", "teardown"):
        _crash_cores.after_the_report(NODEID, when, False)
    assert not fake.core.exists() and not _calls(fake), "the core of a passing test was not deleted, or gdb read it"
    listed = (fake.evidence / _crash_cores.AFTER_PASSING).read_text(encoding="utf-8")
    assert listed.startswith(NODEID + "\t" + CORE + "\t"), listed
    assert not fake.folder.exists()

    _crash_cores.after_the_report(NODEID, "call", True)  # no core yet: noted
    assert "no core file" in (fake.folder / "notes.txt").read_text(encoding="utf-8")
    fake.core.write_bytes(b"\x7fELF fake core")  # the crash is found only at the teardown
    _crash_cores.after_the_report(NODEID, "teardown", False)
    assert (fake.folder / (CORE + ".gdb.txt")).is_file() and not fake.core.exists(), sorted(p.name for p in fake.folder.iterdir())
    assert len(listed.splitlines()) == len((fake.evidence / _crash_cores.AFTER_PASSING).read_text(encoding="utf-8").splitlines())


def test_without_a_core_folder_nothing_is_done_and_the_session_s_limit_is_the_hard_one(fake, monkeypatch):
    monkeypatch.delenv("INVPW_CORE_DIR")
    _crash_cores.after_the_report(NODEID, "call", True)
    _crash_cores.after_the_report(NODEID, "teardown", False)
    assert fake.core.is_file() and not _calls(fake) and not fake.evidence.exists(), "something was done without $INVPW_CORE_DIR"
    _crash_cores.lift_the_core_limit_of_the_session()
    if sys.platform.startswith("linux"):
        import resource

        soft, hard = resource.getrlimit(resource.RLIMIT_CORE)
        assert soft == hard, "the session's core limit is (%r, %r)" % (soft, hard)
    else:  # Windows has no core limit and no core files: lifting is a no-op that does not raise
        assert os.name == "nt", os.name
