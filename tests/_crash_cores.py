"""TEMPORARY: the core of every crash of an engine the tests start, read by gdb after a test that fails. Remove it with tests/_generation_evidence.py once the
exit by SIGSEGV (-11) of the engine in generate mode on Linux (runs 44985244053 and 45014369018) is understood and fixed.

A release build crashes in silence: MOZ_CRASH, MOZ_RELEASE_ASSERT and a Rust panic write to a null address and print nothing, so stderr cannot tell a crash the
code wanted from a bad access. The core can: `gMozCrashReason` says the reason of a wanted crash, the faulting address and the thread that fell say the rest.

* `lift_the_core_limit_of_the_session()`: once, at the start of pytest (tests/conftest.py, `pytest_configure`), on Linux: the soft RLIMIT_CORE of the pytest
  process raised to its hard limit. Every process a test starts inherits it, the engines the CORE launches included (its `generate` passes no limit of its own),
  so a crash of any of them leaves a core where `kernel.core_pattern` says. The Linux e2e jobs (e2e.yml, and gate.yml of the engine series) point it at
  `$INVPW_CORE_DIR` and install gdb.
* `after_the_report(nodeid, when, failed)`: tests/conftest.py calls it after each phase of every test (`pytest_runtest_makereport`). When `$INVPW_CORE_DIR` is set:
  after a phase that FAILED, every `core*` there is read by gdb into `<evidence>/cores/<nodeid>/<core>.gdb.txt` and deleted, and `notes.txt` says what was found
  (no core included); after the teardown of a test that did not fail, the cores left are deleted and listed in `<evidence>/cores/after-passing-tests.txt` (a crash
  in a passing test is information too). `<evidence>` is `$RUNNER_TEMP/invpw-evidence`, the folder the e2e jobs upload.
* `gdb_text(core, into)`: the one gdb path of the tests: the executable is the one the core's header names (else `$INVPW_BINARY_PATH`), and the text holds the
  backtrace of every thread, their names, the signal's address, `gMozCrashReason`, the registers, the shared libraries with their addresses and build ids, and the
  mappings. Only the text is kept: a core of the engine is hundreds of MB.

Best effort: nothing here raises, and nothing here decides a test.
"""
from __future__ import annotations

import contextlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

#: The folder under `$RUNNER_TEMP` the e2e workflows upload (`invpw-evidence-*`, "Keep what the tests saved").
EVIDENCE_FOLDER = "invpw-evidence"
CORES = "cores"
AFTER_PASSING = "after-passing-tests.txt"
#: How long gdb may take to read a core of the engine, and to read its header only.
GDB_TIMEOUT_S = 600
HEADER_TIMEOUT_S = 120
#: What gdb prints from the core: the crashing thread first, then every thread with its name, the signal, the reason of a wanted crash, where libxul is.
GDB_COMMANDS = (
    "set pagination off",
    "set width 0",
    "bt",
    "info threads",
    "thread apply all bt",
    "p $_siginfo",
    "p $_siginfo._sifields._sigfault.si_addr",
    "x/s *(char**)&gMozCrashReason",
    "info registers",
    "x/8i $pc",
    "info sharedlibrary",
    "python print('\\n'.join('%s %s' % (o.filename, o.build_id) for o in gdb.objfiles()))",
    "info proc mappings",
)
_HEADER = re.compile(r"Core was generated by `([^']*)'")
#: The tests a phase of which failed: their teardown reads its cores too.
_FAILED = set()


def lift_the_core_limit_of_the_session():
    """Linux: the soft RLIMIT_CORE of this process raised to its hard limit, inherited by every child. Elsewhere, or if it is refused, nothing."""
    if not sys.platform.startswith("linux"):
        return
    try:
        import resource

        _soft, hard = resource.getrlimit(resource.RLIMIT_CORE)
        resource.setrlimit(resource.RLIMIT_CORE, (hard, hard))
    except (ImportError, OSError, ValueError):
        pass


def core_pattern():
    try:
        return Path("/proc/sys/kernel/core_pattern").read_text(encoding="utf-8").strip()
    except OSError as exc:
        return "unreadable: %r" % (exc,)


def gdb():
    """The gdb command (a list), or None when gdb is not installed."""
    found = shutil.which("gdb")
    return [found] if found else None


def evidence_root():
    base = os.environ.get("RUNNER_TEMP") or tempfile.gettempdir()
    return Path(base) / EVIDENCE_FOLDER / CORES


def folder_name(nodeid):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", nodeid).strip("_")[:150] or "unnamed"


def _cores():
    where = os.environ.get("INVPW_CORE_DIR")
    if not where or not Path(where).is_dir():
        return None, []
    return Path(where), sorted((path for path in Path(where).glob("core*") if path.is_file()), key=lambda path: path.stat().st_mtime)


def executable_of(core, command):
    """The executable the core's header names when it is a file, else `$INVPW_BINARY_PATH` (or `$STEALTHFOX_E2E_BINARY`), else None. Returns (path, how)."""
    header = ""
    try:
        done = subprocess.run(command + ["-batch", "-nx", "-c", str(core)], stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              timeout=HEADER_TIMEOUT_S)
        header = done.stdout.decode("utf-8", "replace")
    except Exception as exc:  # best effort
        header = "header unreadable: %r" % (exc,)
    match = _HEADER.search(header)
    named = match.group(1).split()[0] if match and match.group(1).split() else None
    if named and Path(named).is_file():
        return named, "from the core's header"
    for variable in ("INVPW_BINARY_PATH", "STEALTHFOX_E2E_BINARY"):
        if os.environ.get(variable) and Path(os.environ[variable]).is_file():
            return os.environ[variable], "from $%s (the header names %r)" % (variable, named)
    return None, "none (the header names %r)" % (named,)


def gdb_text(core, into):
    """gdb's text of `core` in `into/<core>.gdb.txt`. One line saying what was done. Does not delete the core."""
    command = gdb()
    size = core.stat().st_size
    if command is None:
        return "core %s (%d bytes, kernel.core_pattern %r) but gdb is not installed" % (core.name, size, core_pattern())
    exe, how = executable_of(core, command)
    argv = command + ["-batch", "-nx"]
    for line in GDB_COMMANDS:
        argv += ["-ex", line]
    argv += ([exe] if exe else []) + ["-c", str(core)]
    target = into / (core.name + ".gdb.txt")
    try:
        done = subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=GDB_TIMEOUT_S)
        target.write_bytes(("executable: %s (%s)\n\n" % (exe, how)).encode("utf-8") + done.stdout)
        return "core %s (%d bytes): gdb exited %d, %d bytes of text in %s; executable %s" % (core.name, size, done.returncode, len(done.stdout), target.name, how)
    except Exception as exc:
        return "core %s (%d bytes): gdb failed: %r" % (core.name, size, exc)


def after_the_report(nodeid, when, failed):
    """After a phase (`setup`, `call`, `teardown`) of the test `nodeid`: see the module's docstring. Never raises."""
    try:
        failed_before = nodeid in _FAILED
        if failed:
            _FAILED.add(nodeid)
        if when == "teardown":
            _FAILED.discard(nodeid)
        where, cores = _cores()
        if where is None:
            return
        if failed or (failed_before and cores):
            into = evidence_root() / folder_name(nodeid)
            into.mkdir(parents=True, exist_ok=True)
            notes = ["%s failed (phase %s); INVPW_CORE_DIR %s, kernel.core_pattern %r, gdb %s" % (nodeid, when, where, core_pattern(), gdb())]
            if not cores:
                notes.append("no core file in %s" % where)
            for core in cores:
                notes.append(gdb_text(core, into))
            with open(str(into / "notes.txt"), "a", encoding="utf-8") as sink:
                sink.write("\n".join(notes) + "\n")
        elif when == "teardown" and cores:
            root = evidence_root()
            root.mkdir(parents=True, exist_ok=True)
            with open(str(root / AFTER_PASSING), "a", encoding="utf-8") as sink:
                for core in cores:
                    sink.write("%s\t%s\t%d bytes (deleted, not read)\n" % (nodeid, core.name, core.stat().st_size))
        else:
            return
        for core in cores:
            with contextlib.suppress(OSError):
                core.unlink()
    except Exception:  # the evidence is best effort: the test's own outcome is what counts
        pass
